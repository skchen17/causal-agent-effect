def authorization_context(name: str) -> AuthorizationContext:
    base = base_authorization_context()
    variants = {
        "draft_only": base,
        "commit_allowed": replace(base, context_id="e62_commit_allowed", commit_allowed=True),
        "alias_disabled": replace(base, context_id="e62_alias_disabled", allowed_resource_aliases={}),
        "untrusted_control_forbidden": replace(base, context_id="e62_untrusted_control_forbidden"),
    }
    if name not in variants:
        raise KeyError(f"Unknown E62 authorization context: {name}")
    return variants[name]


def _tool(
    name: str,
    domain: str,
    description: str,
    parameter_schema: dict[str, Any],
    safe: dict[str, Any],
    unsafe: dict[str, Any],
    unknown: dict[str, Any],
    effects: tuple[str, ...],
) -> ToolSpec:
    return ToolSpec(
        name=name,
        domain=domain,
        description=description,
        parameter_schema=parameter_schema,
        example_safe_call=safe,
        example_unsafe_call=unsafe,
        example_unknown_call=unknown,
        expected_side_effects=effects,
    )

